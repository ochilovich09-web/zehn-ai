let current = 'uz';
const listeners = new Set();

export function setLanguage(lang) {
  if (!DICT[lang]) return;
  current = lang;
  document.documentElement.lang = lang;
  applyTranslations();
  for (const fn of listeners) fn(lang);
  try { localStorage.setItem('zehn.lang', lang); } catch { /* private mode */ }
}

export const getLanguage = () => current;
export const onLanguageChange = (fn) => { listeners.add(fn); return () => listeners.delete(fn); };

/** Tarjima: t('app.send') yoki t('file.tooMany', { n: 5 }) */
export function t(key, vars) {
  let str = DICT[current]?.[key] ?? DICT.uz[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) str = str.replaceAll(`{${k}}`, v);
  return str;
}

/** Sahifadagi data-i18n atributlarini yangilaydi. */
export function applyTranslations(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll('[data-i18n-placeholder]')) node.placeholder = t(node.dataset.i18nPlaceholder);
  for (const node of root.querySelectorAll('[data-i18n-title]')) node.title = t(node.dataset.i18nTitle);
}

/** Saqlangan yoki brauzer tilini aniqlaydi. */
export function detectInitialLanguage() {
  try {
    const saved = localStorage.getItem('zehn.lang');
    if (saved && DICT[saved]) return saved;
  } catch { /* e'tiborsiz */ }
  const nav = (navigator.language || 'uz').slice(0, 2).toLowerCase();
  return DICT[nav] ? nav : 'uz';
}
